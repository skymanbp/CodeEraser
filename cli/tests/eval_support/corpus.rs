//! Corpus resolution for the commit-slice instrument family: which
//! repository is under measurement, which window, and where each
//! frozen doc family lives. Split from mod.rs when the M5-1
//! external-validation machinery pushed it past the file budget.

use super::{eval_doc, git_run};

/// The L1 commit of the self slice — the last commit before any L2
/// work, so the instrument stays outside its own universe.
pub const SELF_UNIVERSE_TIP: &str = "2f40f22b85dcf3fd0979395286223ddf972550ff";

/// The corpus under measurement. Default = this repository from its
/// root (the frozen M4-5 slice, regenerated byte-identical). Setting
/// CE_SLICE_REPO (see colordiff::git_run) retargets at an external
/// corpus and then requires CE_SLICE_NAME (doc suffix), CE_SLICE_TIP
/// (pinned universe tip) and CE_SLICE_BASE (exclusive window base on
/// the first-parent chain — both window ends pinned, and shallow
/// clones only reach so far back). The written doc pins every value.
pub struct Corpus {
    pub name: Option<String>,
    pub tip: String,
    pub base: Option<String>,
}

impl Corpus {
    /// The corpus's frozen document path for one doc family
    /// ("slice", "labels", "baseline-l1", "l2") — one derivation for
    /// generators, gates and cross-doc loads.
    pub fn doc(&self, family: &str) -> String {
        match &self.name {
            Some(name) => eval_doc(&format!("commit-{family}-{name}")),
            None => eval_doc(&format!("commit-{family}")),
        }
    }
}

/// Every committed slice doc paired with its `family` sibling. The
/// sibling MUST exist — a slice without its labels/baseline is an
/// unfinished freeze, and a gate that skips it would go silently
/// blind on a whole corpus.
pub fn corpus_doc_pairs(family: &str) -> Vec<(String, String)> {
    let pairs = doc_pairs(family, true);
    assert!(!pairs.is_empty(), "no committed slice docs");
    pairs
}

/// Like corpus_doc_pairs, but a missing sibling is a PENDING corpus,
/// not an error — for families that freeze later than the slice
/// (an L2 doc lands only once the bar passes on that corpus; the
/// requests doc stayed pending on the invention finding until the
/// anchor floor landed, see EVAL-SET). The self corpus sibling must
/// still exist: that bar is frozen.
pub fn corpus_doc_pairs_frozen(family: &str) -> Vec<(String, String)> {
    let pairs = doc_pairs(family, false);
    let self_doc = format!("../contracts/eval/commit-{family}-v1.json");
    assert!(
        pairs.iter().any(|(_, d)| *d == self_doc),
        "self {family} doc missing"
    );
    pairs
}

/// The corpus-name suffix of a frozen doc path
/// ("…/commit-labels-ripgrep-v1.json" → Some("ripgrep"), the self
/// doc → None) — how a gate iterating EVERY corpus resolves the
/// matching compiled review record (resolving via the active corpus
/// would silently read the wrong one — Codex review C3 follow-up).
pub fn doc_corpus_name(path: &str, family: &str) -> Option<String> {
    let stem = path.rsplit('/').next().expect("file name");
    let mid = stem
        .strip_prefix(&format!("commit-{family}"))
        .and_then(|s| s.strip_suffix("-v1.json"))
        .unwrap_or_else(|| panic!("{path}: not a {family} doc"));
    (!mid.is_empty()).then(|| mid.trim_start_matches('-').to_string())
}

fn doc_pairs(family: &str, required: bool) -> Vec<(String, String)> {
    let mut pairs = Vec::new();
    for entry in std::fs::read_dir("../contracts/eval").expect("eval dir") {
        let file = entry.expect("entry").file_name();
        let file = file.to_string_lossy();
        if !(file.starts_with("commit-slice") && file.ends_with("-v1.json")) {
            continue;
        }
        let sibling = file.replace("commit-slice", &format!("commit-{family}"));
        let sibling = format!("../contracts/eval/{sibling}");
        match std::fs::exists(&sibling).expect("probe") {
            true => pairs.push((format!("../contracts/eval/{file}"), sibling)),
            false => assert!(!required, "{file}: missing {family} sibling {sibling}"),
        }
    }
    pairs
}

pub fn corpus() -> Corpus {
    let get = |k: &str| std::env::var(k).ok().filter(|v| !v.trim().is_empty());
    let (name, tip, base) = (
        get("CE_SLICE_NAME"),
        get("CE_SLICE_TIP"),
        get("CE_SLICE_BASE"),
    );
    if get("CE_SLICE_REPO").is_none() {
        assert!(
            name.is_none() && tip.is_none() && base.is_none(),
            "CE_SLICE_NAME/TIP/BASE make no sense without CE_SLICE_REPO"
        );
        return Corpus {
            name: None,
            tip: SELF_UNIVERSE_TIP.into(),
            base: None,
        };
    }
    assert!(
        name.is_some() && tip.is_some() && base.is_some(),
        "CE_SLICE_REPO needs non-empty CE_SLICE_NAME + CE_SLICE_TIP + \
         CE_SLICE_BASE: an unnamed corpus would overwrite the frozen \
         self slice, and an unpinned window end is unreproducible"
    );
    // A movable expression (HEAD, branch, short sha) would make the
    // written doc unreproducible — pin both ends to full OIDs now.
    let pin = |rev: String| {
        let full = git_run(
            &["rev-parse", "--verify", &format!("{rev}^{{commit}}")],
            false,
        );
        full.trim().to_string()
    };
    Corpus {
        name,
        tip: pin(tip.expect("tip")),
        base: base.map(pin),
    }
}
