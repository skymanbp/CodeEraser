-- | Rust's `str::to_lowercase`, exactly (plan v2.33 W2-text stage G):
-- the Markdown ladder folds a reference label with it (CommonMark's case
-- fold as the measuring side spelled it), and GHC's `toLower` is another
-- mapping (simple case mapping only, another Unicode version). Each
-- character maps as Rust's `char::to_lowercase` does (W6's
-- `CE.Similar.Lower`, one table for both: U+0130 to two characters,
-- the only one that does) and a capital sigma by the str-level
-- Final_Sigma rule: final (ς) when a cased character precedes it and
-- none follows, case-ignorable characters skipped on both sides. The
-- tables were generated from rustc 1.94.1's std over every scalar value
-- (the classes inferred from to_lowercase itself: a character is
-- case-ignorable when `A` + it + `Σ` ends final and it + `Σ` does not,
-- cased when it + `Σ` ends final); the differential gate (tests subrepo
-- unit/graph/resolve/text.rs) asks both sides about every scalar value
-- again, so a toolchain update that moves a mapping is seen, not
-- inherited.
module CE.Resolve.Lower (rustLower) where

import CE.Resolve.Chars (hexRanges, within)
import CE.Similar.Lower (rustToLower)
import qualified Data.IntMap.Strict as IM

rustLower :: String -> String
rustLower = go []
 where
  go _ [] = []
  go before (c : after) = lowered before c after <> go (c : before) after

-- | One character in its context: the text before it (nearest first)
-- and after it.
lowered :: String -> Char -> String -> String
lowered before c after
  | c == '\x3A3' = [if ignorableThenCased before && not (ignorableThenCased after) then '\x3C2' else '\x3C3']
  | otherwise = rustToLower c

-- | `case_ignorable_then_cased`: past the case-ignorable characters, a
-- cased one.
ignorableThenCased :: String -> Bool
ignorableThenCased cs = case dropWhile (within ignorable) cs of
  (c : _) -> within cased c
  [] -> False

-- | Case_Ignorable (464 ranges) and Cased (151; read only past the
-- ignorable ones).
ignorable, cased :: IM.IntMap Int
ignorable = hexRanges (unwords [ignorableA, ignorableB])
cased = hexRanges (unwords [casedA])

