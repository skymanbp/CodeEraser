-- | Three character classes of the measuring side's standard library,
-- exactly (plan v2.33 W6): Rust's `char::is_numeric` (General_Category
-- Nd, Nl or No), `char::is_lowercase` (the derived Lowercase property)
-- and `char::is_uppercase` (Uppercase). The identifier splitter of the
-- same-role advisor (CE.Similar.Terms) cuts with them, and GHC's
-- `isNumber` / `isLower` / `isUpper` read other tables (another Unicode
-- version; Ll / Lu instead of the derived properties, so U+00AA, U+02B0
-- and the circled letters differ). The ranges were generated from rustc
-- 1.94.1's std over every scalar value (a range may run across the
-- surrogate gap, which holds no scalar); the differential gate (tests
-- subrepo unit/similar/bags_diff.rs, the chars leg) asks both sides about
-- every scalar value again, so a toolchain update that moves a property
-- is seen, not inherited. Alphabetic-or-Numeric is CE.Resolve.Chars.
module CE.Similar.Chars (isRustNumeric, isRustLower, isRustUpper) where

import Data.Char (ord)
import Numeric (readHex)
import qualified Data.IntMap.Strict as IM

isRustNumeric, isRustLower, isRustUpper :: Char -> Bool
isRustNumeric = within numeric
isRustLower = within lower
isRustUpper = within upper

-- | The range starting at or below the character covers it.
within :: IM.IntMap Int -> Char -> Bool
within ranges c = case IM.lookupLE (ord c) ranges of
  Just (_, hi) -> ord c <= hi
  Nothing -> False

-- | Low and high bound of each range, as hexadecimal words.
ranged :: [String] -> IM.IntMap Int
ranged parts = IM.fromDistinctAscList (pairUp [n | w <- words (unwords parts), (n, "") <- readHex w])
 where
  pairUp (a : b : rest) = (a, b) : pairUp rest
  pairUp _ = []

-- | 146 ranges.
numeric :: IM.IntMap Int
numeric = ranged [numericA]

-- | 677 ranges.
lower :: IM.IntMap Int
lower = ranged [lowerA, lowerB, lowerC, lowerD]

-- | 660 ranges.
upper :: IM.IntMap Int
upper = ranged [upperA, upperB, upperC, upperD]

